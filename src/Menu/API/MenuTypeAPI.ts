import { ObjectResponse } from "../Types/TypesDTO/ObjectResponse";
import { MenuTypeTypes } from "../Types/MenuTypeTypes";
import { BASE_URL_APIS_USER } from "../../constants";

//const URL = 'http://localhost:8080/api/v1/back-app-catalog-core-service/currency-type';
const URL: string = `${BASE_URL_APIS_USER}/menu-type`;

export async function GetMenuTypeId(id: number): Promise<ObjectResponse<MenuTypeTypes> | null> {
    try {
        const response = await fetch(`${URL}/get/${id}`);
        if (response.ok) {
            const data: ObjectResponse<MenuTypeTypes> = await response.json();
            return data;
        } else {
            throw new Error(`La solicitud a la API fallo ${response.status}`);
        }
    } catch (error) {
        console.error("Error al llamar a la API:", error);
        return null;
    }
}

export const GetMenuType = async (
  page: number,
  size: number,
  filters: Partial<MenuTypeTypes>,
  sortOrder: string = '',  
  sortBy?: keyof MenuTypeTypes
): Promise<MenuTypeTypes[]> => {
  const queryParams = new URLSearchParams();

  queryParams.append('page', String(page));
  queryParams.append('size', String(size));

  const validSortOrder = sortOrder === 'ASC' || sortOrder === 'DESC' ? sortOrder : 'ASC';
  queryParams.append('orders', validSortOrder);

  if (sortBy) {
    queryParams.append('sortBy', String(sortBy)); 
  }

  Object.keys(filters).forEach(key => {
    const value = filters[key as keyof MenuTypeTypes];
    if (value) {
      queryParams.append(key, String(value));
    }
  });

  try {
    const response = await fetch(`${URL}?${queryParams.toString()}`);
    if (!response.ok) {
      throw new Error('Error en la respuesta del servidor');
    }
    const data = await response.json();
    return data.content; 
  } catch (error) {
    console.error('Error al obtener los elementos:', error);
    return [];
  }
};


